/** Codes that intentionally have no national flag. */
const NO_FLAG = new Set(["AIN", "ANA", "EOR", "IOP", "IOA", "ROT", "XX", "ZZ"]);

export function toIso2Country(code: string | null | undefined): string | null {
  if (!code) return null;
  const raw = code.trim().toUpperCase();
  if (!raw) return null;
  if (NO_FLAG.has(raw)) return null;
  if (raw.length === 2 && /^[A-Z]{2}$/.test(raw)) {
    // Kosovo uses XK unofficially — still emit regional indicators.
    return raw;
  }
  if (raw.length === 3) return IOC_TO_ISO2[raw] ?? null;
  return null;
}

/** Regional-indicator flag emoji from ISO-2 / IOC code, or null. */
export function flagEmoji(code: string | null | undefined): string | null {
  const iso = toIso2Country(code);
  if (!iso || iso.length !== 2) return null;
  const a = iso.charCodeAt(0);
  const b = iso.charCodeAt(1);
  if (a < 65 || a > 90 || b < 65 || b > 90) return null;
  return String.fromCodePoint(0x1f1e6 + (a - 65), 0x1f1e6 + (b - 65));
}
